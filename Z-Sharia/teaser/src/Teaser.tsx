import React from "react";
import { Audio } from "@remotion/media";
import { AbsoluteFill, Sequence, staticFile } from "remotion";
import { CUES, T } from "./cues";
import { Finale, FINALE_LEN } from "./scenes/Finale";
import { Gamify, GAMIFY_LEN } from "./scenes/Gamify";
import { Hook, HOOK_LEN } from "./scenes/Hook";
import { Journey, JOURNEY_LEN } from "./scenes/Journey";

export const TEASER_LEN = T.end; // 900 frames = 30 s

const SFX_LEN: Record<string, number> = { pop: 15, pop_small: 12, whoosh: 30, coin: 36, click: 9, rise: 75 };

export const Teaser: React.FC = () => (
  <AbsoluteFill style={{ background: "white" }}>
    <Sequence name="1 Hook" from={T.hook} durationInFrames={HOOK_LEN}>
      <Hook />
    </Sequence>
    <Sequence name="2 Journey" from={T.journey} durationInFrames={JOURNEY_LEN}>
      <Journey />
    </Sequence>
    <Sequence name="3 Gamify" from={T.gamify} durationInFrames={GAMIFY_LEN}>
      <Gamify />
    </Sequence>
    <Sequence name="4 Finale" from={T.finale} durationInFrames={FINALE_LEN}>
      <Finale />
    </Sequence>

    {/* music bed (generated by audio/make_audio.py) */}
    <Audio src={staticFile("audio/music.wav")} volume={1} />
    {/* sound effects pinned to on-screen events */}
    {CUES.map((c, i) => (
      <Sequence key={i} name={`sfx ${c.sfx}: ${c.note}`} from={c.at} durationInFrames={SFX_LEN[c.sfx]} layout="none">
        <Audio src={staticFile(`audio/sfx_${c.sfx}.wav`)} volume={c.vol} />
      </Sequence>
    ))}
  </AbsoluteFill>
);
